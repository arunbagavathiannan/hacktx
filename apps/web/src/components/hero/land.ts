function inRing(lng: number, lat: number, ring: Ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

export function isLand(lat: number, lng: number) {
  // Antarctica as a band, so the bottom of the globe isn't empty.
  if (lat < -72) return true;
  return LAND.some((ring) => inRing(lng, lat, ring));
}
